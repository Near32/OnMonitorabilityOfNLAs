"""Copy each scaled run's figures and results here, and tabulate every number
the paper cites (exp*/expected.json) per run, grouped by the paper section
whose text cites it.   python results_scaled/make_numbers.py
"""
import glob, json, os, re, shutil, statistics


def lookup(path, keys):  # same as check_results.lookup, which runs on import
    v = json.load(open(path))
    for k in keys:
        if k == "se" and isinstance(v, list):
            return statistics.stdev(v) / len(v) ** 0.5
        v = v[k]
    return v

S = "/tmp/claude-1000/-home-kevin-Developments-OnMonitorabilityOfNLAs/ae7c0047-3349-4cb6-9328-b9f5db898b74/scratchpad"
TEX = os.path.expanduser("~/Developments/NLA-confabulations/report/V2")
RUNS = [("scratch, paper sizes", "paper"), ("N = 100", "n100"),
        ("N = 200", "n200"), ("N = 400", "n400")]
RUNS = [(lab, f"{S}/scale_{d}", d) for lab, d in RUNS
        if os.path.exists(f"{S}/scale_{d}/check.log")]

for _, src, d in RUNS:
    for sub in ("results", "artefacts/rivals.json"):
        p = f"{src}/{sub}"
        dst = f"results_scaled/{d}/{sub}"
        if os.path.isdir(p):
            shutil.copytree(p, dst, dirs_exist_ok=True)
        elif os.path.exists(p):
            os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy(p, dst)
