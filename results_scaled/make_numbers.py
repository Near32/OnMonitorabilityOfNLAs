# section of every line of the paper, in reading order
lines = []
def read(name, sec):
    for n, l in enumerate(open(f"{TEX}/{name}.tex", encoding="utf-8"), 1):
        m = re.match(r"\\input\{(\w+)\}", l.strip())
        if m:
            sec = read(m.group(1), sec); continue
        m = re.match(r"\\(sub)?section\{(.*)\}", l.strip())
        if m:
            sec = (m.group(2) if not m.group(1) else sec.split(" > ")[0] + " > " + m.group(2))
        if not l.lstrip().startswith("%"):
            lines.append((sec, l, f"{name}.tex:{n}"))
    return sec
read("paper0a", "Abstract")

def cites(e):
    """(section, file:line) of every line citing the number, body sections first."""
    want = e["expected"]
    if "." not in want and len(want) < 3:  # bare counts like 35 match everywhere
        return []
    alts = [re.escape(want)]
    if e["paper"].startswith("method: judge confirms"):
        alts.append(f"{round(float(want) * 100)}" + r"\\%")
    if "(deg)" in e["paper"]:  # the text rounds degrees: "1.6 degrees", "22 degrees"
        alts += [re.escape(f"{float(want):.{k}f}") + r"\s*deg" for k in (0, 1)]
    pat = re.compile(r"(?<![\d.])(" + "|".join(alts) + r")(?![\d])")
    hits = [(s, at) for i, (s, l, at) in enumerate(lines) if pat.search(l)]
    return sorted(hits, key=lambda h: not h[0].startswith(("Method", "Experiments")))

def fmt(v, want):
    nd = len(want.split(".")[1]) if "." in want else 0
    return f"{v:.{max(nd, 3) if abs(v) < 1e-2 else nd}{'e' if abs(v) < 1e-3 and v else 'f'}}"

NOT = "Not cited verbatim (written as words, or as a count)"
groups = {}
for exp in sorted(glob.glob("exp*/expected.json")):
    for e in json.load(open(exp)):
        hits = cites(e)
        sec, at = hits[0] if hits else (NOT, "")
        row = [e["paper"], e["expected"]]
        for _, src, _ in RUNS:
            try:
                row.append(fmt(float(lookup(f"{src}/{e['file']}", e["path"])), e["expected"]))
            except Exception:
                row.append("–")
        row.append(", ".join(dict.fromkeys(a for _, a in hits)))
        groups.setdefault(sec, []).append((at, row))

def line_no(at):
    f, _, n = at.partition(":")
    return (f, int(n or 0))

out = ["# The paper's numbers at each sample size", "",
       "Generated by `results_scaled/make_numbers.py` from each run's results.",
       "Each number sits under the Method or Experiments section that cites it",
       "(else the first section that does); the last column lists every line of",
       "the paper source (report/V2) containing it; that is a text match, so a",
       "coincidental hit (e.g. 0.75 in a figure width) is possible. Figures for",
       "each run are in `results_scaled/<run>/results/figures/`. The paper's own",
       "runs used 40 conversations (rivals) and 60 (hard negatives, paraphrases);",
       "the N runs use N for both, so N-way retrieval lineups grow with N.", ""]
head = ["number", "paper"] + [lab for lab, _, _ in RUNS] + ["cited at"]
pos = {sec: i for i, (sec, _, _) in reversed(list(enumerate(lines)))}
for g in sorted(groups, key=lambda g: pos.get(g, 1e9)):
    out += [f"## {g}", "", "| " + " | ".join(head) + " |",
            "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |"
            for _, r in sorted(groups[g], key=lambda x: line_no(x[0]) if x[0] else ("~", 0))] + [""]
open("results_scaled/NUMBERS.md", "w").write("\n".join(out))
print("wrote results_scaled/NUMBERS.md for", [d for _, _, d in RUNS])
